# Tarea Semana 9 - Arreglo simple
# Creamos un arreglo con los valores solicitados
arreglo = [10, 20, 30, 40, 50]

# Mostrar el valor en la posición 1
print("Valor en la posición 1:", arreglo[1])

# Recorrer todo el arreglo desde la primera posición
print("Elementos del arreglo:")
for i in range(len(arreglo)):
    print(arreglo[i])